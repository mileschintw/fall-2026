"""Checks that AI_NOTE.md is filled in.  Run:  python3 check_note.py

It checks that each answer is there and at least 5 words long, not what it says.
Exit code 0 means the check passed. You do not edit this file; it is what GitHub runs.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NOTE_FILE = 'AI_NOTE.md'
SECTIONS = 4


def note():
    path = os.path.join(HERE, NOTE_FILE)
    if not os.path.exists(path):
        print('NOTE: AI_NOTE.md is missing.')
        return False
    text = open(path, encoding='utf-8').read()
    sections = re.split(r'^## ', text, flags=re.M)[1:]
    if len(sections) < SECTIONS:
        print('NOTE: AI_NOTE.md should have its %d numbered sections.' % SECTIONS)
        return False
    bad = []
    for s in sections:
        title = s.split('\n', 1)[0].strip()
        m = re.search(r'^Answer:(.*?)(?=^## |\Z)', s, flags=re.M | re.S)
        answer = (m.group(1) if m else '').replace('(write here)', '')
        if len(re.findall(r"[A-Za-z0-9']+", answer)) < 5:
            bad.append(title)
    if bad:
        print('NOTE: these answers are still empty or too short (5 words or more each):')
        for t in bad:
            print('   ' + t)
        return False
    print('NOTE: complete. Thank you.')
    return True


if __name__ == '__main__':
    sys.exit(0 if note() else 1)
