"""Checks that a priority queue from priority_queue.py is put together correctly.
(Provided. You do not edit this file. The tests use it, and you can too, while you debug.)

    from pq_checks import assert_pq_valid, show_pq
    assert_pq_valid(pq)     # raises AssertionError, with a reason, if anything is wrong
    print(show_pq(pq))      # the heap and the position dict, one entry per line
"""


def _key(entry):
    return (entry[0], entry[1])


def problems(pq):
    """Return a list of everything wrong with pq (an empty list means it looks right)."""
    found = []
    if not isinstance(pq, dict) or set(pq) != {'heap', 'position', 'counter'}:
        return ["a priority queue is a dict with exactly the keys 'heap', 'position' and 'counter'"]
    heap, position, counter = pq['heap'], pq['position'], pq['counter']
    if not isinstance(heap, list) or not isinstance(position, dict):
        return ["'heap' should be a list and 'position' a dict"]
    for i, entry in enumerate(heap):
        if not isinstance(entry, list) or len(entry) != 3:
            return ['heap[%d] is %r; an entry is a list [priority, order, item]' % (i, entry)]
    orders = [entry[1] for entry in heap]
    if len(set(orders)) != len(orders):
        found.append('two entries have the same order number; each insert should get a new one')
    if orders and max(orders) >= counter:
        found.append("an entry's order (%d) is not less than 'counter' (%d)" % (max(orders), counter))
    for i in range(1, len(heap)):
        parent = (i - 1) // 2
        if _key(heap[i]) < _key(heap[parent]):
            found.append('heap order is broken: heap[%d] = %r comes before its parent heap[%d] = %r'
                         % (i, heap[i], parent, heap[parent]))
            break
    if len(position) != len(heap):
        found.append("'position' has %d items but the heap has %d entries" % (len(position), len(heap)))
    for i, entry in enumerate(heap):
        item = entry[2]
        if item not in position:
            found.append("%r is in heap[%d] but not in 'position'" % (item, i))
        elif position[item] != i:
            found.append("position[%r] is %r, but %r is in heap[%d]" % (item, position[item], item, i))
    return found


def assert_pq_valid(pq):
    found = problems(pq)
    if found:
        raise AssertionError('the priority queue is not valid:\n  ' + '\n  '.join(found)
                             + '\n' + show_pq(pq))


def show_pq(pq):
    try:
        lines = ['heap:']
        for i, entry in enumerate(pq['heap']):
            lines.append('  [%d] %r' % (i, entry))
        lines.append('position: %r' % (pq['position'],))
        lines.append('counter: %r' % (pq['counter'],))
        return '\n'.join(lines)
    except (KeyError, TypeError):
        return repr(pq)
