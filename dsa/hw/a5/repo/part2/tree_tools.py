"""Helpers for working with trees. Every function here is iterative, so it also
works on very deep trees (a chain of 5,000 nodes is fine). You do not edit this file.

A tree node is a dict with three keys:
    {'payload': value, 'left': node_or_None, 'right': node_or_None}
An empty tree is None.
"""


def create_tree_node(value, left=None, right=None):
    return {'payload': value, 'left': left, 'right': right}


def inorder_values(root):
    """Return the payloads of the tree in left, node, right order, as a list."""
    out = []
    stack = []
    node = root
    while stack or node is not None:
        while node is not None:
            stack.append(node)
            node = node['left']
        node = stack.pop()
        out.append(node['payload'])
        node = node['right']
    return out


def tree_size(root):
    """Return how many nodes the tree has."""
    count = 0
    todo = [root] if root is not None else []
    while todo:
        node = todo.pop()
        count += 1
        if node['left'] is not None:
            todo.append(node['left'])
        if node['right'] is not None:
            todo.append(node['right'])
    return count


def tree_height(root):
    """Return the height in edges: a single node is 0 and the empty tree is -1."""
    best = -1
    todo = [(root, 0)] if root is not None else []
    while todo:
        node, depth = todo.pop()
        best = max(best, depth)
        if node['left'] is not None:
            todo.append((node['left'], depth + 1))
        if node['right'] is not None:
            todo.append((node['right'], depth + 1))
    return best
