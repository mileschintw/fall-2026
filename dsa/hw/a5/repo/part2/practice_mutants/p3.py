"""The reference binary search tree that your tests are written for.

You do not edit this file. Your tests (in test_bst.py) import these five functions.
These docstrings, together with the README, are the specification.
"""
from tree_tools import create_tree_node


def bst_insert(root, value):
    """Insert value into the tree and return the root.

    An empty tree (None) gets a new node, which is returned. Otherwise the tree is
    changed in place and its root is returned. A value already in the tree is ignored.
    Values are compared with < and ==, so ints, floats and strings all work.
    """
    if root is None:
        return create_tree_node(value)
    node = root
    while True:
        if value == node['payload']:
            return root
        side = 'left' if value < node['payload'] else 'right'
        if node[side] is None:
            node[side] = create_tree_node(value)
            return root
        node = node[side]


def bst_search(root, value):
    """Return the node holding value, or None if value is not in the tree."""
    node = root
    while node is not None:
        if value == node['payload']:
            return node
        node = node['left']
    return None


def bst_min(root):
    """Return the node holding the smallest value, or None for an empty tree."""
    if root is None:
        return None
    node = root
    while node['left'] is not None:
        node = node['left']
    return node


def bst_max(root):
    """Return the node holding the largest value, or None for an empty tree."""
    if root is None:
        return None
    node = root
    while node['right'] is not None:
        node = node['right']
    return node


def bst_delete(root, value):
    """Delete value from the tree and return the root of the result.

    If value is not in the tree, nothing changes. Otherwise the tree is changed in
    place. The result is a binary search tree holding every other value, and it is
    never taller than the tree was before.
    """
    parent, node = None, root
    while node is not None and not value == node['payload']:
        parent = node
        node = node['left'] if value < node['payload'] else node['right']
    if node is None:
        return root
    if node['left'] is not None and node['right'] is not None:
        succ_parent, succ = node, node['right']
        while succ['left'] is not None:
            succ_parent, succ = succ, succ['left']
        node['payload'] = succ['payload']
        parent, node = succ_parent, succ
    child = node['left'] if node['left'] is not None else node['right']
    if parent is None:
        return child
    if parent['left'] is node:
        parent['left'] = child
    else:
        parent['right'] = child
    return root
