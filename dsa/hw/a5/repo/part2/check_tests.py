"""Check your tests (test_bst.py) on your own computer.

    python3 check_tests.py              run every check below and print a summary
    python3 check_tests.py gate         your tests must pass on the reference
    python3 check_tests.py mutant p1    your tests must catch practice mutant p1 (p1 to p4)
    python3 check_tests.py note         AI_NOTE.md must be filled in
    python3 check_tests.py mine         (not graded) run your tests on YOUR tree from part1/bst.py

You do not edit this file. It is also what the autograder runs in GitHub.
Exit code 0 means the check passed.
"""
import ast
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
TEST_FILE = 'test_bst.py'
NOTE_FILE = 'AI_NOTE.md'
MIN_TESTS = 8
MUTANTS = ['p1', 'p2', 'p3', 'p4']

ALLOWED_MODULES = {'unittest', 'random', 'time', 'copy', 'itertools', 'math', 'string', 'collections'}
ALLOWED_FROM = {
    'bst_reference': {'bst_insert', 'bst_search', 'bst_min', 'bst_max', 'bst_delete'},
    'tree_tools': {'create_tree_node', 'inorder_values', 'tree_size', 'tree_height'},
}
ALLOWED_DUNDER = {'__name__', '__main__', '__init__'}
BANNED_NAMES = {'open', 'exec', 'eval', 'compile', 'globals', 'locals', 'vars', 'dir', 'getattr',
                'setattr', 'delattr', '__import__', 'input', 'breakpoint', 'sleep'}


def lint(path):
    """Return a list of problems. Your tests may only test the five functions, not look at how they are written."""
    problems = []
    try:
        tree = ast.parse(open(path, encoding='utf-8').read(), path)
    except SyntaxError as e:
        return ['%s has a syntax error on line %s' % (os.path.basename(path), e.lineno)]
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                if a.name.split('.')[0] not in ALLOWED_MODULES:
                    problems.append('line %d: you may not import %s' % (node.lineno, a.name))
        elif isinstance(node, ast.ImportFrom):
            mod = (node.module or '').split('.')[0]
            if mod in ALLOWED_FROM:
                for a in node.names:
                    if a.name not in ALLOWED_FROM[mod]:
                        problems.append('line %d: %s has no %s to import' % (node.lineno, mod, a.name))
            elif mod not in ALLOWED_MODULES:
                problems.append('line %d: you may not import from %s' % (node.lineno, node.module))
        elif isinstance(node, ast.Name):
            if node.id in BANNED_NAMES:
                problems.append('line %d: %s is not allowed in the tests' % (node.lineno, node.id))
            elif node.id.startswith('__') and node.id not in ALLOWED_DUNDER:
                problems.append('line %d: %s is not allowed in the tests' % (node.lineno, node.id))
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            if '__' in node.value.replace('__name__', '').replace('__main__', ''):
                problems.append('line %d: text containing __ is not allowed in the tests' % node.lineno)
        elif isinstance(node, ast.Attribute):
            if node.attr in BANNED_NAMES:
                problems.append('line %d: .%s is not allowed in the tests' % (node.lineno, node.attr))
            elif node.attr.startswith('__') and node.attr not in ALLOWED_DUNDER:
                problems.append('line %d: .%s is not allowed in the tests' % (node.lineno, node.attr))
    return problems


def run_suite(module_file, timeout):
    """Run test_bst.py with module_file standing in for bst_reference.py.
    Returns (status, tests_run, seconds, stderr); status is 'pass', 'fail' or 'timeout'."""
    with tempfile.TemporaryDirectory() as d:
        shutil.copy(os.path.join(HERE, 'tree_tools.py'), d)
        shutil.copy(module_file, os.path.join(d, 'bst_reference.py'))
        shutil.copy(os.path.join(HERE, TEST_FILE), d)
        env = dict(os.environ, PYTHONPATH=d, PYTHONDONTWRITEBYTECODE='1')
        start = time.time()
        try:
            r = subprocess.run([sys.executable, '-m', 'unittest', 'test_bst'], cwd=d, env=env,
                               capture_output=True, text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            return 'timeout', 0, time.time() - start, ''
        seconds = time.time() - start
        m = re.search(r'Ran (\d+) test', r.stderr)
        ran = int(m.group(1)) if m else 0
        return ('pass' if r.returncode == 0 else 'fail'), ran, seconds, r.stderr


def _reference():
    return os.path.join(HERE, 'bst_reference.py')


def gate(verbose=True):
    """True if the tests are allowed to be graded. Also returns the seconds the reference run took."""
    say = print if verbose else (lambda *a: None)
    problems = lint(os.path.join(HERE, TEST_FILE))
    if problems:
        say('GATE: not passed. Tests may only call the five functions; they may not look at how they are written.')
        for p in problems:
            say('   ' + p)
        return False, 0.0
    status, ran, seconds, err = run_suite(_reference(), 60)
    if status == 'timeout':
        say('GATE: not passed. Your tests did not finish in 60 seconds on the reference.')
        return False, seconds
    if status == 'fail':
        say('GATE: not passed. Your tests FAIL on the reference, so a test is wrong (or the rule is misread).')
        say('   Run python3 -m unittest test_bst -v to see which one.')
        return False, seconds
    if ran < MIN_TESTS:
        say('GATE: not passed. Your tests pass, but only %d ran; at least %d are needed.' % (ran, MIN_TESTS))
        return False, seconds
    say('GATE: passed (%d tests pass on the reference in %.1f s).' % (ran, seconds))
    return True, seconds


def mutant(name, verbose=True):
    say = print if verbose else (lambda *a: None)
    ok, seconds = gate(verbose=False)
    if not ok:
        say('MUTANT %s: not counted, because the gate has not passed (run: python3 check_tests.py gate).' % name)
        return False
    path = os.path.join(HERE, 'practice_mutants', name + '.py')
    limit = min(60, max(10, 5 * seconds))
    status, ran, secs, err = run_suite(path, limit)
    if status == 'pass':
        say('MUTANT %s: NOT caught. All your tests still pass on the buggy version. Which rule does it break?' % name)
        return False
    say('MUTANT %s: caught.' % name)
    return True


def note(verbose=True):
    say = print if verbose else (lambda *a: None)
    path = os.path.join(HERE, NOTE_FILE)
    if not os.path.exists(path):
        say('NOTE: AI_NOTE.md is missing.')
        return False
    text = open(path, encoding='utf-8').read()
    sections = re.split(r'^## ', text, flags=re.M)[1:]
    if len(sections) < 4:
        say('NOTE: AI_NOTE.md should have its four numbered sections.')
        return False
    bad = []
    for s in sections:
        title = s.split('\n', 1)[0].strip()
        m = re.search(r'^Answer:(.*?)(?=^## |\Z)', s, flags=re.M | re.S)
        answer = (m.group(1) if m else '').replace('(write here)', '')
        if len(re.findall(r"[A-Za-z0-9']+", answer)) < 5:
            bad.append(title)
    if bad:
        say('NOTE: these answers are still empty or too short (5 words or more each):')
        for t in bad:
            say('   ' + t)
        return False
    say('NOTE: complete. Thank you.')
    return True


def mine():
    """Not graded. Runs your tests with part1/bst.py standing in for the reference."""
    path = os.path.join(HERE, '..', 'part1', 'bst.py')
    if not os.path.exists(path):
        print('MINE: could not find part1/bst.py.')
        return False
    status, ran, seconds, err = run_suite(path, 120)
    if status == 'pass':
        print('MINE: all %d of your tests pass on your own Part 1 tree.' % ran)
        return True
    if status == 'timeout':
        print('MINE: your tests did not finish in 120 seconds on your Part 1 tree. Is one of its operations slow?')
        return False
    print('MINE: some of your tests FAIL on your Part 1 tree. Either the test is wrong or your tree is.')
    print('      If the test passes on the reference (check_tests.py gate), it is your tree. Details:')
    print('\n'.join(err.strip().splitlines()[-25:]))
    return False


def main(argv):
    if len(argv) == 1:
        results = [('gate', gate()[0])]
        results += [('mutant ' + m, mutant(m)) for m in MUTANTS]
        results.append(('note', note()))
        print()
        for name, ok in results:
            print('%-10s %s' % (name, 'ok' if ok else 'NOT YET'))
        return 0 if all(ok for _, ok in results) else 1
    if argv[1] == 'gate':
        return 0 if gate()[0] else 1
    if argv[1] == 'mutant' and len(argv) == 3 and argv[2] in MUTANTS:
        return 0 if mutant(argv[2]) else 1
    if argv[1] == 'note':
        return 0 if note() else 1
    if argv[1] == 'mine':
        return 0 if mine() else 1
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv))
