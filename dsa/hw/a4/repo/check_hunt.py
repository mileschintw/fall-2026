"""Check your work on your own computer.

    python3 check_hunt.py              run every check and print a summary
    python3 check_hunt.py own          your tests (test_regressions.py) pass on your fixed help_desk.py
    python3 check_hunt.py already      test_already_correct.py still passes on your help_desk.py
    python3 check_hunt.py findings     FINDINGS.md rows are complete and each row's test behaves as claimed
    python3 check_hunt.py reflection   the reflection questions in FINDINGS.md are answered

You do not edit this file. It is also what the autograder runs in GitHub. Exit code 0 means passed.
"""
import ast
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
TESTS = 'test_regressions.py'
GIVEN = 'test_already_correct.py'
MIN_TESTS = 3

ALLOWED_MODULES = {'unittest', 'random', 'time', 'copy', 'itertools', 'math', 'string', 'collections', 'help_desk'}
ALLOWED_DUNDER = {'__name__', '__main__', '__init__'}
BANNED_NAMES = {'open', 'exec', 'eval', 'compile', 'globals', 'locals', 'vars', 'dir', 'getattr', 'setattr',
                'delattr', '__import__', 'input', 'breakpoint', 'sleep'}


def lint(path):
    """Tests may call the help desk functions; they may not look at how the code is written."""
    problems = []
    try:
        tree = ast.parse(open(path, encoding='utf-8').read(), path)
    except SyntaxError as e:
        return ['%s has a syntax error on line %s' % (os.path.basename(path), e.lineno)]
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                if a.name.split('.')[0] not in ALLOWED_MODULES:
                    problems.append('line %d: you may not import %s' % (node.lineno, a.name))
        elif isinstance(node, ast.ImportFrom):
            if (node.module or '').split('.')[0] not in ALLOWED_MODULES:
                problems.append('line %d: you may not import from %s' % (node.lineno, node.module))
        elif isinstance(node, ast.Name):
            if node.id in BANNED_NAMES or (node.id.startswith('__') and node.id not in ALLOWED_DUNDER):
                problems.append('line %d: %s is not allowed in the tests' % (node.lineno, node.id))
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            if '__' in node.value.replace('__name__', '').replace('__main__', ''):
                problems.append('line %d: text containing __ is not allowed in the tests' % node.lineno)
        elif isinstance(node, ast.Attribute):
            if node.attr in BANNED_NAMES or (node.attr.startswith('__') and node.attr not in ALLOWED_DUNDER):
                problems.append('line %d: .%s is not allowed in the tests' % (node.lineno, node.attr))
    return problems


def run_suite(test_file, module_file, timeout=60):
    """Run test_file against module_file (copied in as help_desk.py).
    Returns (status, tests_run, seconds, stderr); status is 'pass', 'fail' or 'timeout'."""
    with tempfile.TemporaryDirectory() as d:
        shutil.copy(module_file, os.path.join(d, 'help_desk.py'))
        name = os.path.splitext(os.path.basename(test_file))[0]
        shutil.copy(test_file, os.path.join(d, name + '.py'))
        env = dict(os.environ, PYTHONPATH=d, PYTHONDONTWRITEBYTECODE='1')
        start = time.time()
        try:
            r = subprocess.run([sys.executable, '-m', 'unittest', name], cwd=d, env=env, capture_output=True,
                               text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            return 'timeout', 0, time.time() - start, ''
        m = re.search(r'Ran (\d+) test', r.stderr)
        return ('pass' if r.returncode == 0 else 'fail'), int(m.group(1)) if m else 0, time.time() - start, r.stderr


RUNNER = '''
import sys, unittest, importlib
mod = importlib.import_module(sys.argv[1])
want = sys.argv[2]
found = []
def walk(s):
    for t in s:
        if isinstance(t, unittest.TestSuite):
            walk(t)
        elif t._testMethodName == want:
            found.append(t)
walk(unittest.defaultTestLoader.loadTestsFromModule(mod))
if not found:
    print('MISSING'); sys.exit(3)
res = unittest.TestResult()
unittest.TestSuite(found).run(res)
print('PASS' if res.wasSuccessful() else 'FAIL')
'''


def run_named(test_file, module_file, test_name, timeout=60):
    """Run the one test whose method name is test_name. Returns 'pass', 'fail', 'missing' or 'timeout'."""
    with tempfile.TemporaryDirectory() as d:
        shutil.copy(module_file, os.path.join(d, 'help_desk.py'))
        shutil.copy(test_file, os.path.join(d, 'student_tests.py'))
        open(os.path.join(d, 'runner.py'), 'w').write(RUNNER)
        env = dict(os.environ, PYTHONPATH=d, PYTHONDONTWRITEBYTECODE='1')
        try:
            r = subprocess.run([sys.executable, 'runner.py', 'student_tests', test_name], cwd=d, env=env,
                               capture_output=True, text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            return 'timeout'
        out = r.stdout.strip().split('\n')[-1] if r.stdout.strip() else ''
        return {'PASS': 'pass', 'FAIL': 'fail', 'MISSING': 'missing'}.get(out, 'fail')


def _p(name):
    return os.path.join(HERE, name)


def own(verbose=True):
    say = print if verbose else (lambda *a: None)
    problems = lint(_p(TESTS))
    if problems:
        say('OWN: not passed. Tests may call the help desk functions, but may not look at how they are written.')
        for p in problems:
            say('   ' + p)
        return False
    status, ran, secs, _ = run_suite(_p(TESTS), _p('help_desk.py'))
    if status != 'pass':
        say('OWN: not passed. Your tests do not all pass on your help_desk.py.')
        say('   Run: python3 -m unittest test_regressions -v     (a test may be wrong, or a fix may be unfinished)')
        return False
    if ran < MIN_TESTS:
        say('OWN: not passed. Only %d test(s) ran; at least %d are needed.' % (ran, MIN_TESTS))
        return False
    st2, ran2, _, _ = run_suite(_p(TESTS), _p('help_desk_original.py'))
    failing = '' 
    if st2 == 'fail':
        failing = ' On the ORIGINAL code at least one of them fails, which is what a regression test is for.'
    elif st2 == 'pass':
        failing = ' But on the ORIGINAL code they all pass too, so none of them notices a bug yet.'
    say('OWN: passed (%d tests pass on your code).%s' % (ran, failing))
    return True


def already(verbose=True):
    say = print if verbose else (lambda *a: None)
    if open(_p('help_desk.py'), encoding='utf-8').read() == open(_p('help_desk_original.py'), encoding='utf-8').read():
        say('ALREADY: not counted yet, because help_desk.py is still identical to the original. Fix something first.')
        return False
    status, ran, secs, err = run_suite(_p(GIVEN), _p('help_desk.py'))
    if status == 'pass':
        say('ALREADY: passed (%d tests of behavior that was correct still pass).' % ran)
        return True
    say('ALREADY: not passed. Something that used to work is broken now. Run: python3 -m unittest test_already_correct -v')
    return False


def _table_rows(text):
    rows = []
    for line in text.split('\n'):
        line = line.strip()
        if line.startswith('|') and not re.match(r'^\|[\s\-|]+\|?$', line):
            cells = [c.strip() for c in line.strip('|').split('|')]
            if len(cells) == 6 and cells[0] != '#':
                rows.append(cells)
    return rows


def findings(verbose=True):
    say = print if verbose else (lambda *a: None)
    path = _p('FINDINGS.md')
    if not os.path.exists(path):
        say('FINDINGS: FINDINGS.md is missing.')
        return False
    rows = [r for r in _table_rows(open(path, encoding='utf-8').read()) if any(c for c in r[1:])]
    problems = []
    if len(rows) < 4:
        problems.append('fill in at least 4 rows (found %d)' % len(rows))
    names = set()
    try:
        tree = ast.parse(open(_p(TESTS), encoding='utf-8').read())
        names = {n.name for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)}
    except SyntaxError:
        problems.append('test_regressions.py has a syntax error')
    if not lint(_p(TESTS)) == []:
        problems.append('test_regressions.py does not pass the rules for tests (run: python3 check_hunt.py own)')
    for r in rows:
        num, func, what, source, status, test = r
        status = status.lower().strip('` ')
        test = test.strip('` ')
        if not func or not what:
            problems.append('row %s: say which function and what you think is wrong' % num)
        if status not in ('confirmed', 'refuted', 'unproven'):
            problems.append('row %s: status must be confirmed, refuted or unproven' % num)
            continue
        if status == 'unproven':
            continue
        if test not in names:
            problems.append('row %s: no test named %r in test_regressions.py' % (num, test))
            continue
        fixed = run_named(_p(TESTS), _p('help_desk.py'), test)
        orig = run_named(_p(TESTS), _p('help_desk_original.py'), test)
        if fixed != 'pass':
            problems.append('row %s: %s does not pass on your help_desk.py' % (num, test))
        elif status == 'confirmed' and orig == 'pass':
            problems.append('row %s: marked confirmed, but %s also passes on the original, so it does not show a bug' % (num, test))
        elif status == 'refuted' and orig != 'pass':
            problems.append('row %s: marked refuted, but %s fails on the original, so the original really is wrong' % (num, test))
    if problems:
        say('FINDINGS: not passed.')
        for p in problems:
            say('   ' + p)
        return False
    say('FINDINGS: passed (%d rows, each one checked by running its test).' % len(rows))
    return True


def reflection(verbose=True):
    say = print if verbose else (lambda *a: None)
    path = _p('FINDINGS.md')
    if not os.path.exists(path):
        say('REFLECTION: FINDINGS.md is missing.')
        return False
    text = open(path, encoding='utf-8').read()
    if '## Reflection' not in text:
        say('REFLECTION: the Reflection section is missing.')
        return False
    sections = re.split(r'^## ', text.split('## Reflection', 1)[1], flags=re.M)[1:]
    if len(sections) < 3:
        say('REFLECTION: the three numbered questions are missing.')
        return False
    bad = []
    for s in sections:
        title = s.split('\n', 1)[0].strip()
        m = re.search(r'^Answer:(.*?)(?=^## |\Z)', s, flags=re.M | re.S)
        answer = (m.group(1) if m else '').replace('(write here)', '')
        if len(re.findall(r"[A-Za-z0-9']+", answer)) < 8:
            bad.append(title[:60])
    if bad:
        say('REFLECTION: these answers are empty or too short (8 words or more each):')
        for t in bad:
            say('   ' + t)
        return False
    say('REFLECTION: complete. Thank you.')
    return True


def main(argv):
    checks = {'own': own, 'already': already, 'findings': findings, 'reflection': reflection}
    if len(argv) == 1:
        results = [(n, f()) for n, f in checks.items()]
        print()
        for n, ok in results:
            print('%-11s %s' % (n, 'ok' if ok else 'NOT YET'))
        return 0 if all(ok for _, ok in results) else 1
    if argv[1] in checks:
        return 0 if checks[argv[1]]() else 1
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv))
