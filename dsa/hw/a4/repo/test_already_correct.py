import unittest

from help_desk import (da_create, da_append, da_get, da_to_list, stack_create, stack_push, stack_pop,
                       stack_is_empty, queue_create, queue_enqueue, queue_dequeue, queue_peek, queue_size,
                       desk_create, submit, work_next, next_ticket, open_count, closed_count, closed_ids,
                       brackets_balanced)


class DynamicArrayStillWorks(unittest.TestCase):
    def test_new_array_is_empty(self):
        self.assertEqual(da_to_list(da_create()), [])

    def test_append_and_read_back(self):
        arr = da_create()
        for i in range(60):
            da_append(arr, i * 3)
        self.assertEqual(da_to_list(arr), [i * 3 for i in range(60)])
        self.assertEqual(da_get(arr, 0), 0)
        self.assertEqual(da_get(arr, 59), 177)

    def test_get_outside_the_array_raises(self):
        arr = da_create()
        da_append(arr, 'a')
        da_append(arr, 'b')
        for bad in [-1, -2, 2, 3, 100]:
            with self.assertRaises(IndexError):
                da_get(arr, bad)


class StackStillWorks(unittest.TestCase):
    def test_last_in_first_out(self):
        s = stack_create()
        self.assertTrue(stack_is_empty(s))
        for v in [1, 2, 3]:
            stack_push(s, v)
        self.assertFalse(stack_is_empty(s))
        self.assertEqual([stack_pop(s), stack_pop(s), stack_pop(s)], [3, 2, 1])
        self.assertTrue(stack_is_empty(s))


class QueueStillWorks(unittest.TestCase):
    def test_first_in_first_out(self):
        q = queue_create()
        for v in 'abcde':
            queue_enqueue(q, v)
        self.assertEqual(queue_size(q), 5)
        self.assertEqual(queue_dequeue(q), 'a')
        self.assertEqual(queue_dequeue(q), 'b')
        self.assertEqual(queue_size(q), 3)

    def test_empty_queue_gives_none(self):
        q = queue_create()
        self.assertIsNone(queue_dequeue(q))
        self.assertIsNone(queue_peek(q))
        self.assertEqual(queue_size(q), 0)

    def test_many_items_come_out_in_order_and_the_queue_ends_empty(self):
        q = queue_create()
        for i in range(500):
            queue_enqueue(q, i)
        self.assertEqual([queue_dequeue(q) for _ in range(500)], list(range(500)))
        self.assertEqual(queue_size(q), 0)
        self.assertIsNone(queue_dequeue(q))
        queue_enqueue(q, 'again')
        self.assertEqual(queue_dequeue(q), 'again')


class DeskStillWorks(unittest.TestCase):
    def test_ids_start_at_one_and_go_up(self):
        d = desk_create()
        self.assertEqual([submit(d, t)['id'] for t in 'abc'], [1, 2, 3])
        self.assertEqual(open_count(d), 3)

    def test_tickets_are_worked_in_order(self):
        d = desk_create()
        for t in ['printer', 'wifi', 'password']:
            submit(d, t)
        self.assertEqual(next_ticket(d)['text'], 'printer')
        self.assertEqual(work_next(d)['text'], 'printer')
        self.assertEqual(work_next(d)['text'], 'wifi')
        self.assertEqual(closed_ids(d), [1, 2])
        self.assertEqual(closed_count(d), 2)
        self.assertEqual(open_count(d), 1)

    def test_nothing_to_work_on(self):
        d = desk_create()
        self.assertIsNone(work_next(d))
        self.assertIsNone(next_ticket(d))


class BracketsStillWork(unittest.TestCase):
    def test_some_balanced_texts(self):
        for text in ['', 'no brackets here', '()', '[]{}', '{[()]}', 'f(a[1], {2})']:
            self.assertTrue(brackets_balanced(text), text)

    def test_some_unbalanced_texts(self):
        for text in ['(]', '([)]', '{(})', '(a]']:
            self.assertFalse(brackets_balanced(text), text)


