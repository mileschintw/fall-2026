"""
Part D: The timing experiment.

Run it with:
    python3 timing.py            (takes a few seconds)
    python3 timing.py --quick    (smaller sizes: handy while you are still debugging)

It times three operations on FIVE structures, at several list sizes:

    structures:  your array_list, your linked_list, Python's list,
                 array.array (Python's real array), collections.deque
    operations:  insert at the FRONT, get the MIDDLE value, insert at the END

and then prints one more experiment about memory. You do not edit this file. You READ its output, copy it into
analysis.md, and explain what you see.

How the timing works: each operation is run many times with Python's timeit
module, and the total is divided by the number of runs. The result is
MICROSECONDS PER OPERATION (a microsecond is a millionth of a second).
Operations that must be undone to keep the list the same size (insert then
remove) are timed as a pair and the result is divided by two.

For better numbers: close other programs, plug in your laptop, and run it twice.
Exact times differ between computers and between runs. What matters is how the
times CHANGE as the list gets bigger. If the time stays flat when n grows
10 times, the operation is about O(1). If the time grows about 10 times, it is
about O(n).
"""
import array
import collections
import sys
import timeit

from array_list import *
from linked_list import *

SIZES = [100, 1_000, 10_000, 100_000]
if '--quick' in sys.argv:
    SIZES = [100, 1_000, 10_000]

OPERATIONS = [('front', 'Insert a value at the FRONT (index 0)'),
              ('middle', 'Get the MIDDLE value (index n // 2)'),
              ('end', 'Insert a value at the END')]
PAIR_OPERATIONS = {'front', 'end'}      # timed as insert + remove, then halved


# ----------------------------- the five structures -----------------------------
def your_array_list(n):
    lst = create_array_list()
    for i in range(n):
        array_list_insert_at(lst, i, i)
    if array_list_length(lst) != n:
        raise RuntimeError('array_list_length says %r after %d inserts' % (array_list_length(lst), n))
    return {'front': lambda: (array_list_insert_at(lst, 0, 0), array_list_remove_at(lst, 0)),
            'middle': lambda: array_list_get(lst, n // 2),
            'end': lambda: (array_list_insert_at(lst, n, 0), array_list_remove_at(lst, n))}


def your_linked_list(n):
    lst = create_linked_list()
    for i in range(n):
        linked_list_insert_at(lst, 0, i)      # building at the front is quick for a linked list
    if linked_list_length(lst) != n:
        raise RuntimeError('linked_list_length says %r after %d inserts' % (linked_list_length(lst), n))
    return {'front': lambda: (linked_list_insert_at(lst, 0, 0), linked_list_remove_at(lst, 0)),
            'middle': lambda: linked_list_get(lst, n // 2),
            'end': lambda: (linked_list_insert_at(lst, n, 0), linked_list_remove_at(lst, n))}


def python_list(n):
    values = list(range(n))
    return {'front': lambda: (values.insert(0, 0), values.pop(0)),
            'middle': lambda: values[n // 2],
            'end': lambda: (values.append(0), values.pop())}


def python_array(n):
    values = array.array('i', range(n))
    return {'front': lambda: (values.insert(0, 0), values.pop(0)),
            'middle': lambda: values[n // 2],
            'end': lambda: (values.append(0), values.pop())}


def python_deque(n):
    values = collections.deque(range(n))
    return {'front': lambda: (values.appendleft(0), values.popleft()),
            'middle': lambda: values[n // 2],
            'end': lambda: (values.append(0), values.pop())}


STRUCTURES = [('your array_list', your_array_list, False),
              ('your linked_list', your_linked_list, False),
              ('Python list', python_list, True),
              ('array.array', python_array, True),
              ('deque', python_deque, True)]


# --------------------------------- measuring ---------------------------------
def microseconds_per_operation(function, n, is_builtin, is_pair):
    repeats = max(5, 400_000 // n)
    if is_builtin:
        repeats *= 10                    # the built-ins are fast, so repeat more
    seconds = timeit.timeit(function, number=repeats)
    return seconds / repeats / (2 if is_pair else 1) * 1_000_000


def measure(builder, is_builtin):
    """Returns ({operation: [time at each size]}, problem or None)."""
    results = {operation: [] for operation, _ in OPERATIONS}
    try:
        for n in SIZES:
            functions = builder(n)
            for operation, _ in OPERATIONS:
                results[operation].append(microseconds_per_operation(
                    functions[operation], n, is_builtin, operation in PAIR_OPERATIONS))
    except Exception as error:
        none_results = {operation: [None] * len(SIZES) for operation, _ in OPERATIONS}
        return none_results, '%s: %s' % (type(error).__name__, error)
    return results, None


def print_speed_tables():
    all_results, problems = {}, []
    for name, builder, is_builtin in STRUCTURES:
        print('  timing %s ...' % name, flush=True)
        all_results[name], problem = measure(builder, is_builtin)
        if problem:
            problems.append((name, problem))
    for operation, title in OPERATIONS:
        print('\n%s' % title)
        print('  microseconds per operation')
        print('  %-18s' % 'structure' + ''.join('%14s' % ('n=%s' % format(n, ',')) for n in SIZES))
        for name, _, _ in STRUCTURES:
            cells = ''.join('%14s' % ('n/a' if value is None else format(value, ',.2f'))
                            for value in all_results[name][operation])
            print('  %-18s' % name + cells)
    for name, problem in problems:
        print('\nCould not time %s yet: %s' % (name, problem))


def print_memory():
    n = 1000
    numbers = list(range(n))
    packed = array.array('i', range(n))
    print('\nMemory for %s whole numbers (0 .. %d)' % (format(n, ','), n - 1))
    print('  Python list: %6s bytes for the list itself' % format(sys.getsizeof(numbers), ','))
    print('               + about %s bytes for the int objects it points to'
          % format(sum(sys.getsizeof(x) for x in numbers), ','))
    print('  array.array: %6s bytes (the numbers are stored directly in the array)'
          % format(sys.getsizeof(packed), ','))


def main():
    print('Python %s' % sys.version.split()[0])
    print('Sizes: %s%s' % (', '.join(format(n, ',') for n in SIZES),
                           '   (--quick)' if '--quick' in sys.argv else ''))
    print_speed_tables()
    print_memory()
    print('\nCopy ALL of this output into analysis.md.')


if __name__ == '__main__':
    main()
